# @@ORGANISMS_OVERRIDE@@  (launch_principal.py replaces this line)
LAYER = 23
N = 3
TEMP = 0.7
MAX_NEW = 64
# CORRECTED 2026-07-26 (notes/FUSION_FEATURE_CORRECTION_2026-07-26.md):
